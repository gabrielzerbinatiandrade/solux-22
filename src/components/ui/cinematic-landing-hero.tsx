export interface CinematicHeroProps extends React.HTMLAttributes<HTMLDivElement> {
  preview: React.ReactNode;
  onPlay: () => void;
  brandName?: string;
  tagline1?: string;
  tagline2?: string;
  cardHeading?: string;
  cardDescription?: React.ReactNode;
  metricValue?: number;
  metricLabel?: string;
  ctaHeading?: React.ReactNode;
  ctaDescription?: string;
}

export function CinematicHero({ 
  preview, onPlay,
  brandName = "SOLUX",
  tagline1 = "Obras pesadas,",
  tagline2 = "gestão inteligente.",
  cardHeading = "Controle total. Sem limites.",
  cardDescription = <>O <span className="text-white font-semibold">Solux</span> conecta sua frota, seu financeiro e suas obras em um sistema 100% em nuvem. Mais controle, lucratividade e decisões baseadas em dados reais.</>,
  metricValue = 365,
  metricLabel = "Days Sober",
  ctaHeading = <>Obras pesadas.<br/><span>Gestão sob controle.</span></>,
  ctaDescription = "Da máquina no campo ao resultado no escritório. Conecte sua frota, suas obras e seu financeiro com o Solux.",
  className, 
  ...props 
}: CinematicHeroProps) {
  
  const [motionEnabled,setMotionEnabled] = useState(true);
  const reduced = !motionEnabled;
  const [playbackEnabled,setPlaybackEnabled] = useState(false);
  const containerRef = useRef<HTMLDivElement>(null);
  const mainCardRef = useRef<HTMLDivElement>(null);
  const mockupRef = useRef<HTMLDivElement>(null);
  const requestRef = useRef<number>(0);

  // 1. High-Performance Mouse Interaction Logic (Using requestAnimationFrame)
  useEffect(() => {
    if (reduced) return;
    const handleMouseMove = (e: MouseEvent) => {
      if (window.scrollY > window.innerHeight * 2) return;

      cancelAnimationFrame(requestRef.current);
      
      requestRef.current = requestAnimationFrame(() => {
        if (mainCardRef.current && mockupRef.current) {
          const rect = mainCardRef.current.getBoundingClientRect();
          const mouseX = e.clientX - rect.left;
          const mouseY = e.clientY - rect.top;
          
          mainCardRef.current.style.setProperty("--mouse-x", `${mouseX}px`);
          mainCardRef.current.style.setProperty("--mouse-y", `${mouseY}px`);

          const xVal = (e.clientX / window.innerWidth - 0.5) * 2;
          const yVal = (e.clientY / window.innerHeight - 0.5) * 2;

          gsap.to(mockupRef.current, {
            rotationY: xVal * 12,
            rotationX: -yVal * 12,
            ease: "power3.out",
            duration: 1.2,
          });
        }
      });
    };

    window.addEventListener("mousemove", handleMouseMove);
    return () => {
      window.removeEventListener("mousemove", handleMouseMove);
      cancelAnimationFrame(requestRef.current);
    };
  },[reduced]);

  // 2. Complex Cinematic Scroll Timeline
  useEffect(() => {
    if (reduced) { setPlaybackEnabled(true); return; }
    const isMobile = window.innerWidth < 768;

    const ctx = gsap.context(() => {
      gsap.set(".text-track, .text-days", { autoAlpha: 1 });
      gsap.set(".main-card", { y: window.innerHeight + 200, autoAlpha: 1 });
      gsap.set(".mockup-scroll-wrapper", { autoAlpha: 0 });
      gsap.set(".cta-wrapper", { autoAlpha: 0, scale: 0.8, filter: "blur(30px)" });

      const scrollTl = gsap.timeline({
        scrollTrigger: {
          trigger: containerRef.current,
          start: "top top",
          end: isMobile ? "+=1500" : "+=2200",
          pin: true,
          scrub: 1,
          anticipatePin: 1,
          onUpdate: self => setPlaybackEnabled(self.progress > 0.25 && self.progress < 0.75),
        },
      });

      scrollTl
        .to([".hero-text-wrapper", ".bg-grid-theme"], { scale: 1.035, filter: "blur(8px)", opacity: 0.2, ease: "power2.inOut", duration: 2 }, 0)
        .to(".main-card", { y: 0, ease: "power3.inOut", duration: 2 }, 0)
        .to(".main-card", { width: "100%", height: "100%", borderRadius: "0px", ease: "power3.inOut", duration: 1.5 })
        .fromTo(".mockup-scroll-wrapper",
          { y: 300, z: -500, rotationX: 50, rotationY: -30, autoAlpha: 0, scale: 0.6 },
          { y: 0, z: 0, rotationX: 0, rotationY: 0, autoAlpha: 1, scale: 1, ease: "expo.out", duration: 2.5 }, "-=0.8"
        )
        .to({}, { duration: 1.25 })
        .set(".hero-text-wrapper", { autoAlpha: 0 })
        .set(".cta-wrapper", { autoAlpha: 1 }) 
        .to({}, { duration: .6 })
        .to(".mockup-scroll-wrapper", {
          scale: 0.9, y: -40, z: -200, autoAlpha: 0, ease: "power3.in", duration: 1.2, stagger: 0.05,
        })
        // Responsive card pullback sizing
        .to(".main-card", { 
          width: isMobile ? "92vw" : "85vw", 
          height: isMobile ? "92vh" : "85vh", 
          borderRadius: isMobile ? "32px" : "40px", 
          ease: "expo.inOut", 
          duration: 1.8 
        }, "pullback") 
        .to(".cta-wrapper", { scale: 1, filter: "blur(0px)", ease: "expo.inOut", duration: 1.8 }, "pullback")
        .to(".main-card", { y: -window.innerHeight - 300, ease: "power3.in", duration: 1.5 });

    }, containerRef);

    return () => ctx.revert();
  },[metricValue,reduced]); 

  return (
    <div
      ref={containerRef}
      className={["cinematic-prompt relative w-full h-screen overflow-hidden flex items-center justify-center bg-background text-foreground font-sans antialiased", reduced ? "prompt-reduced" : "", className].filter(Boolean).join(" ")}
      style={{ perspective: "1500px" }}
      {...props}
    >
      <style dangerouslySetInnerHTML={{ __html: INJECTED_STYLES }} />
      <button className="hero-motion-toggle" aria-pressed={motionEnabled} aria-label={motionEnabled?"Pausar animações da apresentação":"Ativar animações da apresentação"} onClick={()=>setMotionEnabled(!motionEnabled)}><GlassLayers/>{motionEnabled ? <Pause size={11}/> : <Play size={11}/>} {motionEnabled ? "Pausar motion" : "Ativar motion"}</button>
      <div className="film-grain" aria-hidden="true" />
      <div className="bg-grid-theme absolute inset-0 z-0 pointer-events-none opacity-50" aria-hidden="true" />

      <div className="hero-text-wrapper impact-intro absolute z-10">
        <div className="impact-copy">
          <div className="impact-eyebrow"><span/> SOFTWARE PARA TERRAPLENAGEM</div>
          <h1 className="impact-title"><span className="text-track">A obra não para.</span><span className="text-days">Sua gestão<br/>acompanha.</span></h1>
          <p className="impact-description">O Solux é um software de gestão para terraplenagem. Controle frota, abastecimentos, obras e financeiro em um só sistema, 100% em nuvem.</p>
          <div className="impact-actions"><a className="impact-primary" href="#contato"><GlassLayers/>Agendar demonstração <ArrowUpRight size={17}/></a><a className="impact-secondary" href="#sistema">Conhecer o Solux <ArrowDown size={15}/></a></div>
          <div className="impact-meta"><span>FROTA</span><i/><span>OBRAS</span><i/><span>FINANCEIRO</span><span className="impact-online"><b/>100% ONLINE</span></div>
        </div>
        <div className="impact-visual">
          <div className="impact-orange-plane"/>
          <div className="impact-photo"><img width="1536" height="1024" fetchPriority="high" src={assetUrl('/images/solux-campo.webp')} alt="Cena ilustrativa de um profissional acompanhando a operação de terraplenagem"/><div className="impact-photo-shade"/><span className="impact-photo-index">SOLUX / EM CAMPO</span><div className="impact-photo-caption"><span>DA OPERAÇÃO AO RESULTADO.</span><strong>Quem move a terra<br/>precisa de visão.</strong></div></div>
          <div className="impact-outline" aria-hidden="true">SX</div>
          <div className="impact-scroll-cue"><span>EXPLORE UMA NOVA VISÃO DA SUA GESTÃO</span><ArrowDown size={16}/></div>
        </div>
      </div>
      {/* BACKGROUND LAYER 2: Tactile CTA Buttons */}
      <div className="cta-wrapper absolute z-10 flex flex-col items-center justify-center text-center w-screen px-4 gsap-reveal pointer-events-auto will-change-transform">
        <span className="prompt-cta-eyebrow">SOLUX · SISTEMA PARA TERRAPLENAGEM</span>
        <h2 className="text-4xl md:text-6xl lg:text-7xl font-bold mb-6 tracking-tight text-silver-matte">
          {ctaHeading}
        </h2>
        <p className="text-muted-foreground text-lg md:text-xl mb-12 max-w-xl mx-auto font-light leading-relaxed">
          {ctaDescription}
        </p>
        <div className="prompt-actions liquid-prompt-actions"><GlassButton href="#contato"><span>Agendar demonstração <ArrowUpRight size={17}/></span></GlassButton><GlassButton href="#funcionalidades"><span>Conhecer o sistema <ArrowDown size={15}/></span></GlassButton></div>
      </div>

      {/* FOREGROUND LAYER: The Physical Deep Blue Card */}
      <div className="absolute inset-0 z-20 flex items-center justify-center pointer-events-none" style={{ perspective: "1500px" }}>
        <div
          ref={mainCardRef}
          className="main-card premium-depth-card relative overflow-hidden gsap-reveal flex items-center justify-center pointer-events-auto w-[92vw] md:w-[85vw] h-[92vh] md:h-[85vh] rounded-[32px] md:rounded-[40px]"
        >
          <div className="card-sheen" aria-hidden="true" />

          <div className="prompt-device-layout">
            <div className="mockup-scroll-wrapper relative w-full flex items-center justify-center z-10" style={{perspective: "1500px"}}>
              <div ref={mockupRef} className="prompt-laptop-device"><CinematicLaptop embedded preview={preview} onPlay={onPlay} playbackEnabled={playbackEnabled}/></div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}














